// composeFile is a single-service compose file in the shape both tools render,
// built from the shared pieces. Its inline content block carries a secrets:
// list with a relative target, which no check may read.
func composeFile() string {
	secrets := []compose.Secret{
		{Name: "app-admin-password", Target: "/mnt/secrets/admin_password", EnvVar: "APP_ADMIN_PASSWORD"},
		{Name: "app-tls", Target: "/mnt/certs/server/tls.pem", EnvVar: "APP_TLS"},
	}
	return "name: \"app\"\n" +
		"services:\n" +
		"  \"app\":\n" +
		"    image: registry.example/app:1.0\n" +
		"    container_name: \"app\"\n" +
		"    user: \"1000:0\"\n" +
		compose.Posture +
		"    ports:\n" +
		"      - \"8080:8080\"\n" +
		compose.ServiceSecrets(secrets) +
		"\n" +
		"    configs:\n" +
		"      - source: app-config\n" +
		"        target: /app/config.yml\n" +
		"configs:\n" +
		"  app-config:\n" +
		"    content: |\n" +
		"      secrets:\n" +
		"        - source: ignored\n" +
		"          target: relative/inside/content\n" +
		compose.TopSecrets(secrets)
}

// unitB is a quadlet unit in solace-util's shape: a [Service] section, and keys
// up to podman 4.7.
