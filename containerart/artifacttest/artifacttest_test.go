// recorder stands in for a test so the Assert wrappers' failures can be read.
type recorder struct {
	testing.TB
	errs []string
}

func (r *recorder) Helper() {}

func (r *recorder) Errorf(format string, args ...any) {
	r.errs = append(r.errs, fmt.Sprintf(format, args...))
}

// TestAssertReportsWithTheName: each wrapper fails once, naming the artifact and
// showing it.
func TestAssertReportsWithTheName(t *testing.T) {
	bad := "[Container]\nPodmanArgs=--privileged\nSecret=x\n"
	for name, assert := range map[string]func(testing.TB){
		"AssertAbsent":         func(r testing.TB) { AssertAbsent(r, "the-unit", bad, Widening()) },
		"AssertComposePosture": func(r testing.TB) { AssertComposePosture(r, "the-unit", bad) },
		"AssertQuadletPosture": func(r testing.TB) { AssertQuadletPosture(r, "the-unit", bad) },
		"AssertQuadletKeys":    func(r testing.TB) { AssertQuadletKeys(r, "the-unit", bad+"Memory=1g\n", "4.7") },
		"AssertSecretTargets":  func(r testing.TB) { AssertSecretTargets(r, "the-unit", bad) },
	} {
		r := &recorder{TB: t}
		assert(r)
		if len(r.errs) != 1 || !strings.HasPrefix(r.errs[0], "the-unit: ") || !strings.Contains(r.errs[0], bad) {
			t.Errorf("%s reported %q, want one failure naming and showing the artifact", name, r.errs)
		}
	}
}

// TestAssertPassesQuietly: the clean shapes report nothing.
func TestAssertPassesQuietly(t *testing.T) {
	r := &recorder{TB: t}
	AssertAbsent(r, "compose", composeFile(), append(Widening(), HostNetwork()...))
	AssertComposePosture(r, "compose", composeFile())
	AssertSecretTargets(r, "compose", composeFile())
	AssertQuadletPosture(r, "unitA", unitA())
	AssertQuadletKeys(r, "unitA", unitA(), "4.5")
	AssertSecretTargets(r, "unitB", unitB())
	if len(r.errs) != 0 {
		t.Errorf("clean artifacts reported %q", r.errs)
	}
}
